"""Assemble the v3 supplementary archive from the project folder on Drive.

The registered analysis files are copied byte-for-byte from TMLR_v3/code, so
their SHA-256 hashes match registration/prereg.json by construction. Data files
are sanitised (absolute Drive paths replaced by placeholders), every text file is
scanned for identifying strings, every file is hashed into MANIFEST.json, and the
archive is verified in a clean temporary copy before it is reported as ready.
"""

from __future__ import annotations

import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile

import config as CFG

TEXT_EXT = {".py", ".md", ".json", ".csv", ".txt", ".ipynb", ".tex", ".yml", ".yaml", ".cfg"}
PATH_RE = re.compile(r"/content/drive/My ?Drive/|/content/v3_local/|/content/")
RESULT_FILES = ["battery.json", "summary.md", "paper_tables.md", "paper_tables.json",
                "fusion_fit_log.csv", "v2_consistency.csv", "resnet50_provenance_mhist.csv"]


def _sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def _sanitise_text(s):
    return PATH_RE.sub(lambda m: "<DRIVE>/" if "drive" in m.group(0) else "<LOCAL>/", s)


def _copy_sanitised(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(src, encoding="utf-8", errors="strict") as fh:
        s = fh.read()
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(_sanitise_text(s))


def _strip_notebook(src, dst):
    """Copy a notebook with all outputs and execution counts removed (outputs can
    contain account names, paths and tokens)."""
    with open(src) as fh:
        nb = json.load(fh)
    for c in nb.get("cells", []):
        if c.get("cell_type") == "code":
            c["outputs"] = []
            c["execution_count"] = None
        c.get("metadata", {}).pop("colab", None)
        c.get("metadata", {}).pop("outputId", None)
        c.get("metadata", {}).pop("id", None)
    nb["metadata"].pop("colab", None)
    nb["metadata"].pop("widgets", None)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w") as fh:
        json.dump(nb, fh, indent=1)


def stage(stage_dir, notebook_dir=None, pilot_zip=None, readme=None, requirements=None):
    if os.path.exists(stage_dir):
        shutil.rmtree(stage_dir)
    os.makedirs(stage_dir)
    log = {"copied": [], "excluded": [], "notes": []}

    # code: byte-for-byte (the registered files must keep their hashes)
    os.makedirs(os.path.join(stage_dir, "code"))
    for f in sorted(glob.glob(os.path.join(CFG.CODE_DIR, "*.py"))):
        shutil.copy2(f, os.path.join(stage_dir, "code", os.path.basename(f)))
    tests = os.path.join(CFG.PROJECT, "tests")
    if os.path.isdir(tests):
        shutil.copytree(tests, os.path.join(stage_dir, "tests"),
                        ignore=shutil.ignore_patterns("__pycache__"))

    # registration (+ Google Drive's own record of the file, if notebook 06 fetched it)
    os.makedirs(os.path.join(stage_dir, "registration"))
    shutil.copy2(CFG.PREREG_PATH, os.path.join(stage_dir, "registration", "prereg.json"))
    dm = os.path.join(CFG.PROJECT, "registration_drive_metadata.json")
    if os.path.exists(dm):
        shutil.copy2(dm, os.path.join(stage_dir, "registration", "drive_metadata.json"))
    else:
        log["notes"].append("no Drive metadata for prereg.json (optional cell in notebook 06 not run)")

    # results
    rd = CFG.RESULTS_DIR
    for f in RESULT_FILES + [os.path.basename(p) for p in glob.glob(os.path.join(rd, "feature_sanity_*.csv"))]:
        p = os.path.join(rd, f)
        if os.path.exists(p):
            _copy_sanitised(p, os.path.join(stage_dir, "results", f))
        else:
            log["notes"].append(f"results/{f} not found (skipped)")
    for p in sorted(glob.glob(os.path.join(rd, "pools", "*.json"))):
        _copy_sanitised(p, os.path.join(stage_dir, "results", "pools", os.path.basename(p)))
    for p in sorted(glob.glob(os.path.join(rd, "pools", "*_logits.npz"))):
        log["excluded"].append({"file": f"results/pools/{os.path.basename(p)}",
                                "bytes": os.path.getsize(p),
                                "reason": "held-out logits; regenerated by notebook 04"})
    rv = os.path.join(rd, "reviewer")
    if os.path.isdir(rv):                      # exploratory reviewer analyses (notebook 07)
        for p in sorted(glob.glob(os.path.join(rv, "*"))):
            if p.endswith((".json", ".md", ".csv")):
                _copy_sanitised(p, os.path.join(stage_dir, "results", "reviewer", os.path.basename(p)))
            elif os.path.isfile(p):
                os.makedirs(os.path.join(stage_dir, "results", "reviewer"), exist_ok=True)
                shutil.copy2(p, os.path.join(stage_dir, "results", "reviewer", os.path.basename(p)))
    figs = os.path.join(rd, "figures")
    if os.path.isdir(figs):
        shutil.copytree(figs, os.path.join(stage_dir, "results", "figures"))

    # manifests (row order, labels, groups, hashes) and feature provenance
    n_texts = 0
    for p in sorted(glob.glob(os.path.join(CFG.MANIFEST_DIR, "*"))):
        dst = os.path.join(stage_dir, "manifests", os.path.basename(p))
        if p.endswith(".json"):
            with open(p) as fh:
                m = json.load(fh)
            if "texts" in m:
                # Dataset text is third-party content: not redistributed. The manifest hash
                # covers (uid, label) only, and uids index the public split, so rows are
                # still reproducible exactly from the named source.
                n_texts += len(m.pop("texts"))
                m["texts_omitted"] = "dataset text not redistributed; regenerate from 'source'"
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "w") as fh:
                fh.write(_sanitise_text(json.dumps(m)))
        else:
            _copy_sanitised(p, dst)
    if n_texts:
        log["excluded"].append({"file": "manifests/<text dataset>.json: field 'texts'", "count": n_texts,
                                "reason": "third-party dataset text not redistributed; "
                                          "regenerated by notebook 03 from the public source"})
    for p in sorted(glob.glob(os.path.join(CFG.FEAT_DIR, "*", "*.json"))):
        ds = os.path.basename(os.path.dirname(p))
        _copy_sanitised(p, os.path.join(stage_dir, "features_provenance", ds, os.path.basename(p)))
    n_feat = len(glob.glob(os.path.join(CFG.FEAT_DIR, "*", "*.npy")))
    log["excluded"].append({"file": "features/<dataset>/<encoder>.npy", "count": n_feat,
                            "reason": "frozen features (~10 GB); regenerated by notebooks 01-03"})

    # extraction run logs (status of every dataset x encoder, timestamped by file name)
    for p in sorted(glob.glob(os.path.join(CFG.LOG_DIR, "*.json"))):
        _copy_sanitised(p, os.path.join(stage_dir, "logs", os.path.basename(p)))

    # notebooks, outputs stripped
    dirs = [d for d in ([notebook_dir] if isinstance(notebook_dir, str) else list(notebook_dir or []))
            + [os.path.join(CFG.PROJECT, "notebooks"), os.path.join(CFG.DRIVE, "Colab Notebooks"), CFG.PROJECT]
            if d and os.path.isdir(d)]
    found = {}
    for d in dirs:                                   # first folder that has a given notebook wins
        for p in sorted(glob.glob(os.path.join(d, "0[0-8]_*.ipynb"))):
            found.setdefault(os.path.basename(p)[:2], p)
    for k, p in sorted(found.items()):
        _strip_notebook(p, os.path.join(stage_dir, "notebooks", os.path.basename(p)))
    log["notebooks_missing"] = [f"{i:02d}" for i in range(9) if f"{i:02d}" not in found]
    if log["notebooks_missing"]:
        log["notes"].append("notebooks missing: " + ", ".join(log["notebooks_missing"]))

    # the pilot's archive, unchanged
    if pilot_zip and os.path.exists(pilot_zip):
        with zipfile.ZipFile(pilot_zip) as z:
            names = [m for m in z.namelist() if not (m.startswith("__MACOSX") or
                     m.endswith(".DS_Store") or m.endswith("/"))]
            tops = {m.split("/")[0] for m in names}
            strip = len(tops) == 1 and all("/" in m for m in names)   # single wrapping folder
            for m in names:
                rel = m.split("/", 1)[1] if strip else m
                out = os.path.join(stage_dir, "pilot", rel)
                os.makedirs(os.path.dirname(out), exist_ok=True)
                with z.open(m) as src, open(out, "wb") as dst:
                    shutil.copyfileobj(src, dst)
    else:
        log["notes"].append("pilot archive not given: pilot/ not included")

    if readme:
        with open(os.path.join(stage_dir, "README.md"), "w") as fh:
            fh.write(readme)
    if requirements:
        with open(os.path.join(stage_dir, "requirements.txt"), "w") as fh:
            fh.write(requirements)
    return log


DATASET_ID_FIELDS = ("uids", "reader", "texts", "classes", "groups", "extra")


def _scannable(path, rel):
    """Text of a staged file as it should be scanned. Row identifiers, file names
    and class names copied from public datasets are third-party content (e.g. NCT
    image names, newsgroup host names), so they are excluded; everything we wrote
    is scanned in full."""
    if rel.startswith("manifests" + os.sep):
        if path.endswith(".csv"):
            return ""                      # row, uid, label, group: all dataset-derived
        try:
            m = json.load(open(path))
            return json.dumps({k: v for k, v in m.items() if k not in DATASET_ID_FIELDS})
        except Exception:
            pass
    return open(path, encoding="utf-8", errors="ignore").read()


def _parse_time(t):
    """Timestamps in provenance records are written by time.strftime on Colab,
    whose clock is UTC by default; the registration time is explicit UTC."""
    import datetime as dt
    if not t or not isinstance(t, str):
        return None
    t = t.strip().replace("Z", "+00:00")
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M:%S"):
        try:
            d = dt.datetime.strptime(t, fmt)
            return d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)
        except ValueError:
            pass
    try:
        d = dt.datetime.fromisoformat(t)
        return d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)
    except ValueError:
        return None


def timeline(stage_dir):
    """Registration -> extraction -> analysis, from what is in the archive and on Drive.
    Writes registration/timeline.json and returns it. Any feature file saved before the
    registration time is listed under 'extracted_before_registration' (must be disclosed)."""
    import datetime as dt
    reg = json.load(open(os.path.join(stage_dir, "registration", "prereg.json")))
    t_reg = _parse_time(reg["registered_utc"])
    feats = []
    for p in sorted(glob.glob(os.path.join(stage_dir, "features_provenance", "*", "*.json"))):
        m = json.load(open(p))
        feats.append({"dataset": os.path.basename(os.path.dirname(p)),
                      "encoder": os.path.splitext(os.path.basename(p))[0],
                      "saved_utc": m.get("saved"), "_t": _parse_time(m.get("saved"))})
    # Features without their own timestamp (the text arm wrote none) are bounded from below by the build
    # time of the dataset manifest they were extracted from: extraction cannot precede the manifest.
    built = {}
    for p in glob.glob(os.path.join(stage_dir, "manifests", "*.json")):
        try:
            built[os.path.splitext(os.path.basename(p))[0]] = _parse_time(json.load(open(p)).get("built"))
        except Exception:
            pass
    for f in feats:
        f["manifest_built_utc"] = built.get(f["dataset"]).isoformat(timespec="seconds") if built.get(f["dataset"]) else None
        f["_lb"] = f["_t"] or built.get(f["dataset"])
    parsed = [f for f in feats if f["_t"] is not None]
    bounded = [f for f in feats if f["_t"] is None and f["_lb"] is not None]
    unknown = [f for f in feats if f["_lb"] is None]
    before = [f for f in feats if t_reg and f["_lb"] is not None and f["_lb"] < t_reg]
    logs = []
    for p in sorted(glob.glob(os.path.join(CFG.LOG_DIR, "extract_*.json"))):
        stamp = os.path.basename(p)[len("extract_"):-len(".json")]
        try:
            logs.append(dt.datetime.strptime(stamp, "%Y%m%d_%H%M%S").replace(tzinfo=dt.timezone.utc))
        except ValueError:
            pass
    bat = os.path.join(stage_dir, "results", "battery.json")
    t_bat = _parse_time(json.load(open(bat)).get("generated")) if os.path.exists(bat) else None
    iso = lambda d: d.isoformat(timespec="seconds") if d else None
    out = {
        "registration_utc": iso(t_reg),
        "registration_file_mtime_utc": iso(dt.datetime.fromtimestamp(os.path.getmtime(CFG.PREREG_PATH),
                                                                       tz=dt.timezone.utc)),
        "feature_files": len(feats), "feature_files_with_timestamp": len(parsed),
        "first_feature_saved_utc": iso(min(f["_t"] for f in parsed)) if parsed else None,
        "last_feature_saved_utc": iso(max(f["_t"] for f in parsed)) if parsed else None,
        "feature_files_bounded_by_manifest_build_time": len(bounded),
        "feature_files_without_any_time": len(unknown),
        "earliest_manifest_built_utc": (min(d for d in built.values() if d).isoformat(timespec="seconds")
                                        if any(built.values()) else None),
        "extracted_before_registration": [{k: v for k, v in f.items() if k not in ("_t", "_lb")} for f in before],
        "extraction_runs_utc": [iso(d) for d in logs],
        "extraction_runs_before_registration": [iso(d) for d in logs if t_reg and d < t_reg],
        "analysis_battery_generated_utc": iso(t_bat),
        "clock_note": "provenance and battery timestamps were written by time.strftime on Colab, whose clock is UTC "
                      "by default; the registration time is recorded in UTC",
    }
    dmp = os.path.join(stage_dir, "registration", "drive_metadata.json")
    if os.path.exists(dmp):
        dm = json.load(open(dmp))
        out["registration_drive_created_utc"] = dm.get("createdTime")
        out["registration_drive_md5_matches_shipped_file"] = dm.get("md5_matches_local")
    out["all_features_after_registration"] = bool(feats) and not before and not unknown
    with open(os.path.join(stage_dir, "registration", "timeline.json"), "w") as fh:
        json.dump(out, fh, indent=1)
    return out


def anonymity_scan(stage_dir, forbidden):
    """Whole-word, case-insensitive search for identifying terms and e-mail
    addresses in every text file of the archive."""
    hits = []
    pats = [(w, re.compile(r"(?<![A-Za-z0-9])" + re.escape(w.strip()) + r"(?![A-Za-z0-9])", re.I))
            for w in forbidden if w.strip()]
    emails = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
    for root, _, files in os.walk(stage_dir):
        for f in files:
            p = os.path.join(root, f)
            rel = os.path.relpath(p, stage_dir)
            if os.path.splitext(f)[1].lower() not in TEXT_EXT:
                continue
            s = _scannable(p, rel)
            for w, pat in pats:
                for m in pat.finditer(s):
                    ctx = s[max(0, m.start() - 40): m.end() + 40].replace("\n", " ")
                    hits.append((rel, w, ctx))
            if not rel.startswith("pilot" + os.sep):
                for m in emails.finditer(s):
                    if not m.group(0).endswith(("example.com", "anon.org")):
                        hits.append((rel, "email", m.group(0)))
    return hits


def write_manifest(stage_dir, log):
    files = []
    for root, _, fs in os.walk(stage_dir):
        for f in sorted(fs):
            p = os.path.join(root, f)
            rel = os.path.relpath(p, stage_dir)
            if rel == "MANIFEST.json":
                continue
            files.append({"file": rel, "bytes": os.path.getsize(p), "sha256": _sha(p)})
    man = {"built_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
           "n_files": len(files), "total_bytes": sum(f["bytes"] for f in files),
           "files": sorted(files, key=lambda f: f["file"]),
           "excluded": log["excluded"], "notes": log["notes"]}
    with open(os.path.join(stage_dir, "MANIFEST.json"), "w") as fh:
        json.dump(man, fh, indent=1)
    return man


def zip_dir(stage_dir, out_zip, top="supplementary"):
    if os.path.exists(out_zip):
        os.remove(out_zip)
    with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for root, _, fs in os.walk(stage_dir):
            for f in sorted(fs):
                p = os.path.join(root, f)
                z.write(p, os.path.join(top, os.path.relpath(p, stage_dir)))
    return os.path.getsize(out_zip)


def verify_archive(out_zip, extra_args=()):
    tmp = tempfile.mkdtemp()
    with zipfile.ZipFile(out_zip) as z:
        z.extractall(tmp)
    root = os.path.join(tmp, "supplementary")
    env = dict(os.environ)
    env.pop("V3_DRIVE", None)
    r = subprocess.run([sys.executable, os.path.join(root, "code", "verify_v3.py"), "--root", root,
                        *extra_args], capture_output=True, text=True, env=env, cwd=root)
    shutil.rmtree(tmp, ignore_errors=True)
    return r.returncode, r.stdout, r.stderr
